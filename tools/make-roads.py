def ll(lat, lng):
    """위경도 → 지도 좌표 (js 의 latLngToSvg 와 같은 식)"""
    return [round(((lng-125.8)*70+10)*10)/10.0, round(((38.8-lat)*69+10)*10)/10.0]

def find(tok):
    """'수원시팔달구' / '서울 서초구' / (위도, 경도) → [x,y]"""
    if isinstance(tok, tuple): return ll(tok[0], tok[1])
    if " " in tok:
        sd, nm = tok.split(" ", 1)
        code = SIDO[sd]
        key = code + ":" + nm
        if key not in CENT: raise KeyError(tok)
        return CENT[key]
    hits = [k for k in CENT if k.split(":",1)[1] == tok]
    if len(hits) != 1: raise KeyError(tok + (" (여러 곳: %d)" % len(hits) if hits else " (없음)"))
    return CENT[hits[0]]

