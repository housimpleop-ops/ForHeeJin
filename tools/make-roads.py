def smooth(pts):
    """꺾인 선을 부드러운 곡선으로 (Catmull-Rom → 베지에)"""
    if len(pts) < 3:
        return "M" + " L".join("%.1f %.1f" % (p[0], p[1]) for p in pts)
    d = "M%.1f %.1f" % (pts[0][0], pts[0][1])
    for i in range(len(pts)-1):
        p0 = pts[i-1] if i > 0 else pts[0]
        p1, p2 = pts[i], pts[i+1]
        p3 = pts[i+2] if i+2 < len(pts) else p2
        c1 = (p1[0] + (p2[0]-p0[0])/6.0, p1[1] + (p2[1]-p0[1])/6.0)
        c2 = (p2[0] - (p3[0]-p1[0])/6.0, p2[1] - (p3[1]-p1[1])/6.0)
        d += "C%.1f %.1f %.1f %.1f %.1f %.1f" % (c1[0], c1[1], c2[0], c2[1], p2[0], p2[1])
    return d

def build(group, kind):
    out, bad = [], []
    for name, toks in group:
        pts = []
        for t in toks:
            try: pts.append(find(t))
            except KeyError as e: bad.append("%s: %s" % (name, e))
        if len(pts) >= 2:
            out.append({"n": name, "k": kind, "d": smooth(pts)})
    return out, bad

